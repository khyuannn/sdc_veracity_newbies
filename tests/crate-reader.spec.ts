import { test, expect } from './isolated-test'
import { loginDemo, changeDemoRole } from './demo-helpers'

test('simulated crate reader, review, transfer and product counting work together', async ({ page, context, baseURL }) => {
  test.setTimeout(120000)
  await page.setViewportSize({ width: 1200, height: 950 })
  const id = `crate-reader-${Date.now()}`
  const tag = `DEMO-${id.toUpperCase()}`
  await loginDemo(page, 'manager')
  const imported = await context.request.post('/api/backend/imports', { headers: { Origin: baseURL! }, data: { kind: 'products', rows: [{ id, name: 'Reader Demo Bottles', recorded: 12 }] } })
  expect(imported.ok()).toBeTruthy()
  await page.goto('/crates')
  const before = await (await context.request.get('/api/backend/crates')).json()
  await expect(page.getByText('Simulated input · no hardware connected')).toBeVisible()
  await page.getByRole('button', { name: 'Register crate', exact: true }).click()
  await page.getByLabel('Register tag ID').fill(tag)
  await page.getByLabel('Crate product').selectOption(id)
  await page.getByLabel('Declared quantity', { exact: true }).fill('12')
  await page.getByLabel('Initial location').fill('Stockroom')
  await page.getByRole('button', { name: 'Save crate registration' }).click()
  await expect(page.getByText('Crate registered. Scan its demo tag to retrieve the record.')).toBeVisible()
  await page.getByLabel('Demo tag', { exact: true }).selectOption(tag)
  await page.getByLabel('Reader location', { exact: true }).fill('Rack B')
  await page.getByRole('button', { name: 'Simulate RFID scan' }).click()
  const detail = page.getByTestId('crate-detail')
  await expect(detail.getByRole('heading', { name: 'Reader Demo Bottles' })).toBeVisible()
  await expect(detail.getByText('Location review needed', { exact: true })).toBeVisible()
  let state = await (await context.request.get('/api/backend/crates')).json()
  expect(state.crates.find((c: { tag: string }) => c.tag === tag).location).toBe('Stockroom')
  await page.getByLabel('Transfer destination').fill('Rack B')
  await page.getByLabel('Transfer note').fill('Whole crate moved for shelf replenishment')
  await page.getByRole('button', { name: 'Confirm transfer', exact: true }).click()
  await expect(detail.getByText('Stockroom → Rack B', { exact: true })).toBeVisible()
  await expect(detail.getByText('Location review needed', { exact: true })).toHaveCount(0)
  await page.screenshot({ path: 'generated-artifacts/rfid-desktop.png', fullPage: true })
  await page.getByRole('link', { name: 'Check this product’s stock' }).click()
  await expect(page.getByLabel('Product', { exact: true })).toHaveValue(id)
  await expect(page.getByRole('region', { name: 'Product crate locations' }).getByRole('link', { name: /Rack B/ })).toBeVisible()
  page.on('dialog', dialog => dialog.accept())
  await page.getByRole('link', { name: /Rack B.*View crate/ }).click()
  await expect(detail.getByRole('heading', { name: 'Reader Demo Bottles' })).toBeVisible()
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByLabel('Demo tag', { exact: true }).selectOption(tag)
  await page.getByLabel('Reader location', { exact: true }).fill('Rack B')
  await page.getByRole('button', { name: 'Simulate RFID scan' }).click()
  await expect(detail.getByRole('heading', { name: 'Reader Demo Bottles' })).toBeVisible()
  await expect(detail.getByText('Location review needed', { exact: true })).toHaveCount(0)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
  await page.screenshot({ path: 'generated-artifacts/rfid-mobile.png', fullPage: true })
  const color = await page.getByLabel('Reader location', { exact: true }).evaluate(el => getComputedStyle(el).color)
  expect(color).not.toBe('rgb(0, 0, 0)')
  await page.getByLabel('Demo tag', { exact: true }).selectOption('DEMO-UNKNOWN-TAG')
  await page.getByRole('button', { name: 'Simulate RFID scan' }).click()
  await expect(page.getByText('Unregistered tag: DEMO-UNKNOWN-TAG', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Scan activity', exact: true }).click()
  await expect(page.getByText('Recent reader observations', { exact: true })).toBeVisible()
  state = await (await context.request.get('/api/backend/crates')).json()
  expect(state.crates).toHaveLength(before.crates.length + 1)
  expect(state.scans).toHaveLength(before.scans.length + 3)
  const inventory = await (await context.request.get('/api/backend/state')).json()
  expect(inventory.products.find((p: { id: string }) => p.id === id).recorded).toBe(12)
  await page.reload()
  await expect(page.getByRole('button', { name: `Open crate ${tag}` })).toBeVisible()
  await changeDemoRole(page, 'owner')
  await page.goto('/crates')
  await expect(page.getByRole('button', { name: 'Simulate RFID scan' })).toBeDisabled()
  await expect(page.getByRole('button', { name: 'Register crate', exact: true })).toBeDisabled()
  const denied = await context.request.post('/api/backend/crates', { headers: { Origin: baseURL! }, data: { action: 'scan', tag, source: 'simulated', station: 'Rack B', requestId: `owner-denied-${Date.now()}` } })
  expect(denied.status()).toBe(403)
})
